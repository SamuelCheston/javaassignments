public class U1_01_Average {
  public static void main(String[] args) {
    double num1 = 5.0;
    double num2 = 10.0;
    double num3 = 15.0;

    double average = (num1 + num2 + num3) / 3;

    System.out.println("The average of " + num1 + ", " + num2 + ", and " + num3 + " is: " + average);
  }
}
